const assert=require('node:assert/strict');
const {matchesQuery,filterMessages,safeName,nextAfterDeletion}=require('./app.js');
const m={id:'one',dateKey:'2024-03-12',to:'Grace <grace@example.com>',sender:'Ada <ada@example.com>',cc:'team@example.com',subject:'Meeting notes',bodyText:'Budget & forecast approved today',plain:'',attachments:[{name:'report.pdf'}]};
for(const query of ['from:ADA to:grace subject:"meeting notes" has:attachment','body:"forecast approved"','cc:team attachment:report.pdf','budget today','content:forecast','has:attachments',''])assert.equal(matchesQuery(m,query),true,query);
for(const query of ['from:grace','to:ada','subject:budget','has:noattachment','body:report.pdf','has:unknown','budget missing'])assert.equal(matchesQuery(m,query),false,query);
assert.equal(matchesQuery({...m,attachments:[]},'has:noattachment'),true);
assert.equal(matchesQuery({...m,attachments:[]},'has:attachment'),false);
const items=[m,{...m,id:'two',dateKey:'2024-04-01'},{...m,id:'three',dateKey:''}];
assert.deepEqual(filterMessages(items,'','2024-03-12','2024-03-12').map(x=>x.id),['one']);
assert.deepEqual(filterMessages(items,'','2024-03-13','').map(x=>x.id),['two']);
assert.deepEqual(filterMessages(items,'','','2024-03-31').map(x=>x.id),['one']);
assert.deepEqual(filterMessages(items,'missing','',''),[]);
assert.deepEqual(filterMessages(items,'','','').map(x=>x.id),['two','one','three']);
assert.deepEqual(filterMessages(items,'','2025-01-01','2024-01-01'),[]);
assert.equal(safeName('../../escape.txt'),'escape.txt');
assert.equal(safeName('CON.txt'),'_CON.txt');
console.log('Search, inclusive date ranges, sorting, and export filename checks passed.');
const ordered=['first','middle','last'], records=ordered.map(id=>({id}));
assert.equal(nextAfterDeletion(ordered,'first',records.slice(1)).id,'middle');
assert.equal(nextAfterDeletion(ordered,'middle',[records[0],records[2]]).id,'last');
assert.equal(nextAfterDeletion(ordered,'last',records.slice(0,2)).id,'middle');
assert.equal(nextAfterDeletion(ordered,'first',[records[2]]).id,'last');
assert.equal(nextAfterDeletion(ordered,'middle',[records[0]]).id,'first');
assert.equal(nextAfterDeletion(ordered,'first',[]),null);
assert.equal(nextAfterDeletion(ordered,'unknown',[records[1]]).id,'middle');
console.log('Auto-advance: first, middle, last, bulk deletion, filtered results, and empty list passed.');
